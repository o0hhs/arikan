-- +goose Up
-- Advertising agents on top of the campaign tags: the admin hands each agent a login and a
-- password for a panel of their own, and links campaigns (their ad placements) to them with
-- a percent of the sales. A linked campaign's applied payments credit the agent -- the
-- percent is snapshotted per payment, so a later change of the link's percent does not
-- rewrite what was already earned.
CREATE TABLE campaign_agents (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  login         TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  note          TEXT NOT NULL DEFAULT '',
  disabled      INTEGER NOT NULL DEFAULT 0 CHECK (disabled IN (0, 1)),
  created_at    BIGINT NOT NULL,
  updated_at    BIGINT NOT NULL
);

-- What one applied payment earned one agent. payment_id is unique, so a payment pays once;
-- sale_amount is the payment's worth in kopecks (Stars at the referral programme's rate),
-- amount is the agent's share of it. A refund takes the credit back rather than leaving it.
CREATE TABLE agent_commissions (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  agent_id    BIGINT NOT NULL REFERENCES campaign_agents(id) ON DELETE CASCADE,
  campaign_id BIGINT NOT NULL REFERENCES campaign_tags(id) ON DELETE CASCADE,
  payment_id  BIGINT UNIQUE REFERENCES payments(id) ON DELETE SET NULL,
  kind        TEXT NOT NULL CHECK (kind IN ('bought', 'renewed')),
  percent     BIGINT NOT NULL CHECK (percent BETWEEN 1 AND 100),
  sale_amount BIGINT NOT NULL CHECK (sale_amount >= 0),
  amount      BIGINT NOT NULL CHECK (amount >= 0),
  currency    TEXT NOT NULL DEFAULT 'RUB',
  created_at  BIGINT NOT NULL,
  reverted_at BIGINT
);
CREATE INDEX agent_commissions_agent ON agent_commissions(agent_id, id DESC);
CREATE INDEX agent_commissions_campaign ON agent_commissions(campaign_id);

-- A payout the admin recorded by hand: what the agent was handed outside the panel.
CREATE TABLE agent_payouts (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  agent_id   BIGINT NOT NULL REFERENCES campaign_agents(id) ON DELETE CASCADE,
  amount     BIGINT NOT NULL CHECK (amount > 0),
  note       TEXT NOT NULL DEFAULT '',
  created_at BIGINT NOT NULL
);

-- The agents' panel sessions, beside the admin's own (0001_baseline).
CREATE TABLE agent_sessions (
  id_hash      TEXT PRIMARY KEY,
  agent_id     BIGINT NOT NULL REFERENCES campaign_agents(id) ON DELETE CASCADE,
  csrf_token   TEXT NOT NULL,
  created_at   BIGINT NOT NULL,
  last_seen_at BIGINT NOT NULL,
  expires_at   BIGINT NOT NULL,
  ip           TEXT NOT NULL,
  user_agent   TEXT NOT NULL
);

-- Which agent a campaign belongs to and for what percent of its sales. Both may be NULL:
-- a plain campaign (the admin's own ads) has neither.
ALTER TABLE campaign_tags
  ADD COLUMN agent_id     BIGINT REFERENCES campaign_agents(id) ON DELETE SET NULL,
  ADD COLUMN agent_percent BIGINT CHECK (agent_percent IS NULL OR (agent_percent BETWEEN 1 AND 100));

-- +goose Down
ALTER TABLE campaign_tags
  DROP COLUMN agent_percent,
  DROP COLUMN agent_id;
DROP TABLE agent_sessions;
DROP TABLE agent_payouts;
DROP TABLE agent_commissions;
DROP TABLE campaign_agents;
