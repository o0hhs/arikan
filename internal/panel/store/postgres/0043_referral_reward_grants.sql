-- +goose Up
-- What a days rule owes a referrer: a temporary subscription on the tariff the REFEREE
-- bought, for the days the rule gives. The row is the whole queue and the whole suspension
-- record, so a restart loses nothing:
--   * queued rows wait for the referrer's streak to reach them; the order is the bought
--     tariff's price, dearest first, then arrival (id), so a cheaper later purchase can
--     never downgrade a running reward;
--   * the row that is running holds the subscription the referrer had before it (the
--     before_* columns), which is restored when its days run out: an active trial comes
--     back with the days it had left, an expired subscription comes back expired;
--   * a refunded referee payment takes its grant back (reverted_at), and the streak after
--     it closes up.
-- price is the tariff's price in kopecks at the moment the reward was earned, kept because
-- a later price change must not reorder rewards already owed.
CREATE TABLE referral_reward_grants (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  referrer_tg_id BIGINT NOT NULL REFERENCES referral_accounts(tg_id) ON DELETE CASCADE,
  referral_id    BIGINT NOT NULL REFERENCES referrals(id) ON DELETE CASCADE,
  payment_id     BIGINT UNIQUE REFERENCES payments(id) ON DELETE SET NULL,
  rule_id        TEXT NOT NULL DEFAULT '',
  -- The tariff the referee bought: what the referrer is switched onto for the reward.
  tariff_id      BIGINT REFERENCES tariffs(id) ON DELETE SET NULL,
  days           BIGINT NOT NULL CHECK (days > 0),
  price          BIGINT NOT NULL DEFAULT 0 CHECK (price >= 0),
  status         TEXT NOT NULL DEFAULT 'queued' CHECK (status IN ('queued','running','done')),
  -- run_at is when the grant's days start; ends_at when they end (null while queued).
  run_at         BIGINT NOT NULL DEFAULT 0,
  ends_at        BIGINT,
  reward_id      BIGINT REFERENCES referral_rewards(id) ON DELETE SET NULL,
  reverted_at    BIGINT,
  created_at     BIGINT NOT NULL,
  updated_at     BIGINT NOT NULL,
  -- The referrer's own subscription as it was before the reward, restored at its end.
  -- before_user_id null: the referrer had no subscription and the reward made one.
  -- The pair (before_user_id set, before_status '') is what marks that case: users.status is
  -- never empty, so a suspended subscription always carries the status it had.
  before_user_id          BIGINT REFERENCES users(id) ON DELETE SET NULL,
  before_status           TEXT NOT NULL DEFAULT '',
  before_tariff_id        BIGINT REFERENCES tariffs(id) ON DELETE SET NULL,
  before_traffic_limit    BIGINT,
  before_device_limit     BIGINT,
  before_speed_limit      BIGINT,
  before_reset_strategy   TEXT NOT NULL DEFAULT '',
  before_device_mode      TEXT NOT NULL DEFAULT '',
  before_period_days      BIGINT NOT NULL DEFAULT 0,
  before_period_start     BIGINT NOT NULL DEFAULT 0,
  before_expires_at       BIGINT,
  before_billing_day      BIGINT
);
-- The queue of one referrer, in the order it runs: dearest first, then arrival.
CREATE INDEX referral_reward_grants_queue ON referral_reward_grants(referrer_tg_id, status, price DESC, id);
CREATE INDEX referral_reward_grants_payment ON referral_reward_grants(payment_id);
-- What is running now, for the advance pass: a handful of rows at most.
CREATE INDEX referral_reward_grants_running ON referral_reward_grants(ends_at) WHERE status = 'running';

-- A subscription the programme made for a referrer who had none (a days reward that has
-- nowhere of the referrer's own to land): its own source says it is neither a purchase nor
-- a trial nor an access code.
ALTER TABLE users DROP CONSTRAINT users_source_check;
ALTER TABLE users ADD CONSTRAINT users_source_check CHECK (source IN ('admin', 'bot', 'trial', 'import', 'free', 'code', 'referral'));

