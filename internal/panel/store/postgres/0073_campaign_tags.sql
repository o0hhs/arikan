-- +goose Up
-- Outbounds the admin added by a share link (vless://, vmess://, trojan://, ss:// and the
-- rest mihomo reads): an inbound can send its traffic through one the way it does through
-- another node's relay. Link is the admin's own text, kept as it was pasted — the node
-- parses it with mihomo's own subscription parser, the panel knows nothing of the
-- protocols. Name is what the panel shows: the link's own remark unless the admin typed one.
CREATE TABLE outbounds (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       TEXT NOT NULL,
  link       TEXT NOT NULL,
  enabled    BIGINT NOT NULL DEFAULT 1 CHECK (enabled IN (0,1)),
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL
);

-- Where an inbound's traffic leaves: with neither of these it goes by outbound (direct or
-- warp). A deleted outbound leaves its inbounds on that column's way out, as a deleted
-- node does.
ALTER TABLE "inbounds" ADD COLUMN outbound_id BIGINT REFERENCES outbounds(id) ON DELETE SET NULL;
CREATE INDEX inbounds_outbound ON "inbounds" (outbound_id) WHERE outbound_id IS NOT NULL;

-- +goose Down
DROP INDEX inbounds_outbound;
ALTER TABLE "inbounds" DROP COLUMN outbound_id;
DROP TABLE outbounds;
