-- +goose Up
-- A discount is a sale of its own: the price of some tariffs is lower while it stands.
-- The panel applies it by itself, without a code: the buyer pays the lower price.
--
-- The mass mailing is the discount's own: it says whether the bot reminds about the end of
-- the sale, how long before the end it says so, and to whom it says it.
CREATE TABLE discounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  type TEXT NOT NULL CHECK (type IN ('percent','fixed')),
  value BIGINT NOT NULL CHECK (value > 0),
  currency TEXT NOT NULL DEFAULT '' CHECK (currency IN ('','XTR','RUB')),
  starts_at BIGINT NOT NULL,
  ends_at BIGINT NOT NULL,
  max_uses BIGINT CHECK (max_uses IS NULL OR max_uses > 0),
  used_count BIGINT NOT NULL DEFAULT 0 CHECK (used_count >= 0),
  min_order BIGINT NOT NULL DEFAULT 0 CHECK (min_order >= 0),
  max_discount BIGINT NOT NULL DEFAULT 0 CHECK (max_discount >= 0),
  notify_enabled BIGINT NOT NULL DEFAULT 0 CHECK (notify_enabled IN (0,1)),
  notify_days TEXT NOT NULL DEFAULT '[3,1]',
  notify_audience TEXT NOT NULL DEFAULT 'buyers' CHECK (notify_audience IN ('buyers','subscribers')),
  notify_text TEXT NOT NULL DEFAULT '',
  enabled BIGINT NOT NULL DEFAULT 1 CHECK (enabled IN (0,1)),
  deleted BIGINT NOT NULL DEFAULT 0 CHECK (deleted IN (0,1)),
  created_at BIGINT NOT NULL,
  created_by BIGINT REFERENCES admins(id) ON DELETE SET NULL
);
CREATE INDEX discounts_active ON discounts(enabled, deleted, starts_at, ends_at);

-- The tariffs the discount is about; none: every tariff on sale.
CREATE TABLE discount_tariffs (
  discount_id BIGINT NOT NULL REFERENCES discounts(id) ON DELETE CASCADE,
  tariff_id BIGINT NOT NULL REFERENCES tariffs(id) ON DELETE CASCADE,
  PRIMARY KEY (discount_id, tariff_id)
);
CREATE INDEX discount_tariffs_tariff ON discount_tariffs(tariff_id);

-- Who bought at the lower price: the redemptions are also the mailing's list of buyers.
CREATE TABLE discount_redemptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  discount_id BIGINT NOT NULL REFERENCES discounts(id) ON DELETE CASCADE,
  user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  tg_id BIGINT NOT NULL,
  payment_id BIGINT UNIQUE REFERENCES payments(id) ON DELETE SET NULL,
  status TEXT NOT NULL CHECK (status IN ('reserved','applied','released')),
  redeemed_at BIGINT NOT NULL,
  discount_amount BIGINT NOT NULL DEFAULT 0,
  original_amount BIGINT NOT NULL DEFAULT 0,
  final_amount BIGINT NOT NULL DEFAULT 0,
  currency TEXT NOT NULL DEFAULT ''
);
CREATE INDEX discount_redemptions_discount ON discount_redemptions(discount_id, redeemed_at);
CREATE INDEX discount_redemptions_user ON discount_redemptions(user_id, redeemed_at);
CREATE INDEX discount_redemptions_tg ON discount_redemptions(discount_id, tg_id) WHERE status='applied';

-- A reminder told once: the discount, the account and the kind of the reminder.
CREATE TABLE discount_notices (
  discount_id BIGINT NOT NULL REFERENCES discounts(id) ON DELETE CASCADE,
  tg_id BIGINT NOT NULL,
  kind TEXT NOT NULL,
  sent_at BIGINT NOT NULL,
  PRIMARY KEY (discount_id, tg_id, kind)
);
CREATE INDEX discount_notices_sent ON discount_notices(sent_at);

