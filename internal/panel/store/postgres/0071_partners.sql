-- +goose Up
-- The franchise's ground: a partner and a bot of theirs. Their subscribers come to the
-- panel's bot with the partner's code; every payment of such an account credits the
-- partner a share of it, kept in kopecks with the ledger that made the balance.
-- The bot's own token is kept for the partner's separate bot to be run with; the panel
-- itself answers through its one bot.

CREATE TABLE partners (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       TEXT NOT NULL,
  note       TEXT NOT NULL DEFAULT '',
  created_at BIGINT NOT NULL
);

CREATE TABLE partner_bots (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  partner_id         BIGINT NOT NULL REFERENCES partners(id) ON DELETE CASCADE,
  code               TEXT NOT NULL UNIQUE,      -- the /start code subscribers come with
  bot_username       TEXT NOT NULL DEFAULT '',
  bot_token          TEXT NOT NULL DEFAULT '',
  commission_percent INT NOT NULL DEFAULT 0 CHECK (commission_percent BETWEEN 0 AND 100),
  balance_kop        BIGINT NOT NULL DEFAULT 0,
  enabled            BOOLEAN NOT NULL DEFAULT true,
  created_at         BIGINT NOT NULL
);

CREATE TABLE partner_transactions (
  id             BIGSERIAL PRIMARY KEY,
  partner_bot_id BIGINT NOT NULL REFERENCES partner_bots(id) ON DELETE CASCADE,
  payment_id     BIGINT NOT NULL,
  kind           TEXT NOT NULL,   -- commission
  amount_kop     BIGINT NOT NULL,
  created_at     BIGINT NOT NULL
);

-- Who brought the account: the first partner code wins, as the referral's does.
ALTER TABLE tg_chats ADD COLUMN partner_bot_id BIGINT REFERENCES partner_bots(id);
ALTER TABLE users ADD COLUMN partner_bot_id BIGINT REFERENCES partner_bots(id);
ALTER TABLE payments ADD COLUMN partner_bot_id BIGINT REFERENCES partner_bots(id);

-- +goose Down
ALTER TABLE payments DROP COLUMN IF EXISTS partner_bot_id;
ALTER TABLE users DROP COLUMN IF EXISTS partner_bot_id;
ALTER TABLE tg_chats DROP COLUMN IF EXISTS partner_bot_id;
DROP TABLE IF EXISTS partner_transactions;
DROP TABLE IF EXISTS partner_bots;
DROP TABLE IF EXISTS partners;
