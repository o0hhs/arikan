-- +goose Up
-- Ad campaigns: a link to the bot carries a campaign's code (t.me/<bot>?start=c_<code>);
-- a Telegram account that comes by it with no subscription yet is the campaign's from then
-- on, so its purchases and renewals count to it.
CREATE TABLE campaigns (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code       TEXT NOT NULL UNIQUE CHECK (code ~ '^[a-z0-9_-]{1,32}$'),
  name       TEXT NOT NULL,
  archived   BIGINT NOT NULL DEFAULT 0,
  created_at BIGINT NOT NULL
);
ALTER TABLE tg_chats ADD COLUMN campaign_id BIGINT REFERENCES campaigns(id) ON DELETE SET NULL;
ALTER TABLE tg_chats ADD COLUMN campaign_at BIGINT;
CREATE INDEX tg_chats_campaign ON tg_chats (campaign_id) WHERE campaign_id IS NOT NULL;

-- +goose Down
DROP INDEX tg_chats_campaign;
ALTER TABLE tg_chats DROP COLUMN campaign_at;
ALTER TABLE tg_chats DROP COLUMN campaign_id;
DROP TABLE campaigns;
