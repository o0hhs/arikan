-- Browser checkout: an email account (or a proved subscription token) can buy and renew
-- without Telegram. payments.web marks an invoice opened in the browser, so the provider
-- sends the buyer back to the shop and the invoice limits are not the bot's.

CREATE TABLE web_accounts (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email      TEXT NOT NULL UNIQUE,
  created_at BIGINT NOT NULL
);

CREATE TABLE web_links (
  user_id    BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  account_id BIGINT NOT NULL REFERENCES web_accounts(id) ON DELETE CASCADE,
  created_at BIGINT NOT NULL
);
CREATE INDEX web_links_account ON web_links(account_id);

CREATE TABLE web_codes (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email      TEXT NOT NULL,
  code_hash  TEXT NOT NULL,
  expires_at BIGINT NOT NULL,
  attempts   INT NOT NULL DEFAULT 0,
  created_at BIGINT NOT NULL
);
CREATE INDEX web_codes_email ON web_codes(email, created_at);

CREATE TABLE web_sessions (
  token_hash TEXT PRIMARY KEY,
  account_id BIGINT REFERENCES web_accounts(id) ON DELETE CASCADE,
  tg_id      BIGINT,
  user_id    BIGINT REFERENCES users(id) ON DELETE CASCADE,
  expires_at BIGINT NOT NULL,
  created_at BIGINT NOT NULL,
  CHECK (account_id IS NOT NULL OR tg_id IS NOT NULL OR user_id IS NOT NULL)
);
CREATE INDEX web_sessions_expiry ON web_sessions(expires_at);

