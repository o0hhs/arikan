-- +goose Up
-- An access code: a promo code that opens one tariff the shop keeps hidden (tariffs.on_sale
-- = 0). Its tariff is the single entry of promo_codes.tariff_ids. access_ttl is how long the
-- access a redemption gives lasts, in seconds; 0: while the panel lives.
ALTER TABLE promo_codes ADD COLUMN access_mode TEXT NOT NULL DEFAULT '' CHECK (access_mode IN ('', 'paid', 'free'));
ALTER TABLE promo_codes ADD COLUMN access_ttl BIGINT NOT NULL DEFAULT 0 CHECK (access_ttl >= 0);

-- The codes are a kind of their own: an account may go through the checkout for a tariff it
-- has no access to, and an access code must not be taken for a discount or a bonus.
ALTER TABLE promo_codes DROP CONSTRAINT promo_codes_type_check;
ALTER TABLE promo_codes ADD CONSTRAINT promo_codes_type_check
  CHECK (type IN ('days', 'traffic', 'percent', 'fixed', 'access_paid', 'access_free'));
-- More than one tariff makes an access code ambiguous, and a code without one opens
-- nothing: the ids are read without a JSON parser, so the column must look like an array of
-- one (tariff_ids holds JSON as text, like every other column of the table).
ALTER TABLE promo_codes ADD CONSTRAINT promo_codes_access_tariff
  CHECK (type NOT IN ('access_paid', 'access_free') OR tariff_ids ~ '^\s*\[\s*[0-9]+\s*\]\s*$') NOT VALID;
ALTER TABLE promo_codes VALIDATE CONSTRAINT promo_codes_access_tariff;
-- An access code is not a discount, so access_mode follows the type; access_ttl only means
-- something for an access code.
ALTER TABLE promo_codes ADD CONSTRAINT promo_codes_access_mode
  CHECK ((type IN ('access_paid', 'access_free')) = (access_mode <> '')) NOT VALID;
ALTER TABLE promo_codes VALIDATE CONSTRAINT promo_codes_access_mode;
ALTER TABLE promo_codes ADD CONSTRAINT promo_codes_access_ttl
  CHECK (type IN ('access_paid', 'access_free') OR access_ttl = 0) NOT VALID;
ALTER TABLE promo_codes VALIDATE CONSTRAINT promo_codes_access_ttl;

-- A subscription an access code gave (access_free) is the admin's to see among the users:
-- its own source tells it from the free plan, which is a different thing (free_plans).
ALTER TABLE users DROP CONSTRAINT users_source_check;
ALTER TABLE users ADD CONSTRAINT users_source_check CHECK (source IN ('admin', 'bot', 'trial', 'import', 'free', 'code'));

-- Who an access code belongs to: one row per redemption, whether the tariff was bought at
-- its price (paid) or given (free). expires_at NULL: the access never ends (the code's
-- ends_at only stops new redemptions). The row is what the checkout and the shop ask; the
-- code's own counter still applies, one use per account when per_user_limit is 1.
CREATE TABLE promo_access (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  promo_id   BIGINT NOT NULL REFERENCES promo_codes(id) ON DELETE CASCADE,
  tariff_id  BIGINT NOT NULL REFERENCES tariffs(id) ON DELETE CASCADE,
  user_id    BIGINT REFERENCES users(id) ON DELETE SET NULL,
  tg_id      BIGINT NOT NULL,
  granted_at BIGINT NOT NULL,
  expires_at BIGINT,
  note       TEXT NOT NULL DEFAULT ''
);
-- One account per code, as the shop and the checkout are re-entered.
CREATE UNIQUE INDEX promo_access_promo_tg ON promo_access(promo_id, tg_id);
CREATE INDEX promo_access_tg ON promo_access(tg_id);
CREATE INDEX promo_access_user ON promo_access(user_id);

