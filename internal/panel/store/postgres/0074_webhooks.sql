-- +goose Up
-- The panel's own webhooks: a subscription sale is queued in the payment's transaction and
-- delivered by a worker, so a slow or a dead site never holds a purchase and a failed
-- delivery is retried instead of lost.
CREATE TABLE webhook_deliveries (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event        TEXT NOT NULL,
  payload      TEXT NOT NULL,  -- the JSON body, exactly as it goes out
  attempts     INT NOT NULL DEFAULT 0,
  next_at      BIGINT NOT NULL,
  created_at   BIGINT NOT NULL,
  delivered_at BIGINT,
  last_error   TEXT NOT NULL DEFAULT ''
);

CREATE INDEX webhook_deliveries_due ON webhook_deliveries (next_at) WHERE delivered_at IS NULL;

