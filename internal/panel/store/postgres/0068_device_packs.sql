-- +goose Up
-- Device packs buy a subscription more device places than its tariff has. The pack rides
-- the subscription: its price adds to the tariff's on every invoice (a pack month is its
-- price, part of every day of the term), and the places it bought widen the subscription's
-- own device limit. The choice is made again on every invoice, so a renewal without a
-- pack takes the extra places back.

CREATE TABLE device_packs (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title       TEXT NOT NULL,
  slots       INT NOT NULL,
  price_rub   BIGINT NOT NULL,  -- kopecks a month
  price_stars BIGINT,           -- Stars a month; NULL: rubles only
  sort        BIGINT NOT NULL DEFAULT 0,
  on_sale     BOOLEAN NOT NULL DEFAULT true,
  archived    BOOLEAN NOT NULL DEFAULT false,
  created_at  BIGINT NOT NULL
);

-- The two packs of the roadmap: +2 places (five devices) and +7 (ten).
