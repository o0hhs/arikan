-- +goose Up
-- Support access (internal/panel/support): a temporary access the admin opens for whoever
-- helps them, with no password and no SSH. The token is shown once (ms_ + 40 base62) and only
-- its hash is kept. level is what the operator may do: view reads, change also writes,
-- terminal adds a root shell on the servers in terminal_targets ('panel' or 'node:<id>').
-- A grant is live while revoked_at is NULL and expires_at is in the future; one live grant at
-- a time (a new one revokes the one before). entered_at is the one browser entry the link
-- allows; operator_seen_at is the first use of any kind (the admin is told once);
-- ended_noted_at is when the end (revoked or expired) was written to the journal and told.
CREATE TABLE support_grants (
  id               BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token_hash       TEXT    NOT NULL UNIQUE,
  admin_id         BIGINT  NOT NULL REFERENCES admins(id) ON DELETE CASCADE,
  level            TEXT    NOT NULL CHECK (level IN ('view', 'change', 'terminal')),
  show_people      BOOLEAN NOT NULL DEFAULT false,
  terminal_targets TEXT[]  NOT NULL DEFAULT '{}',
  note             TEXT    NOT NULL DEFAULT '',
  created_at       BIGINT  NOT NULL,
  expires_at       BIGINT  NOT NULL,
  entered_at       BIGINT,
  operator_seen_at BIGINT,
  last_used_at     BIGINT,
  last_ip          TEXT    NOT NULL DEFAULT '',
  revoked_at       BIGINT,
  ended_noted_at   BIGINT
);
CREATE INDEX support_grants_admin ON support_grants (admin_id);
CREATE INDEX support_grants_created ON support_grants (created_at);

-- A support operator's browser session belongs to its grant and goes with it.
ALTER TABLE sessions ADD COLUMN support_grant_id BIGINT REFERENCES support_grants(id) ON DELETE CASCADE;
CREATE INDEX sessions_support_grant ON sessions (support_grant_id) WHERE support_grant_id IS NOT NULL;

-- +goose Down
DROP INDEX sessions_support_grant;
ALTER TABLE sessions DROP COLUMN support_grant_id;
